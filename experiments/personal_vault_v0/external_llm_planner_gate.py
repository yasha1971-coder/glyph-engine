#!/usr/bin/env python3
import argparse, collections, json, subprocess
from pathlib import Path


def glyph_query(root, probe):
    out=subprocess.check_output([
        "python3","experiments/personal_vault_v0/query_rlb3x_object.py",
        "--rlb3x",str(root/"bwt.rlb3x"),
        "--locate-core",str(root/"locate.loc2"),
        "--objects",str(root/"objects.json"),
        "--pattern-hex",probe.encode("utf-8").hex(),
    ],text=True)
    return json.loads(out)


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("root",type=Path)
    ap.add_argument("--oracle",type=Path,default=Path("experiments/personal_vault_v0/human_intent_cases_v0.json"))
    ap.add_argument("--plans",type=Path,default=Path("experiments/personal_vault_v0/llm_planner_replay_v1.json"))
    a=ap.parse_args(); root=a.root

    oracle_doc=json.loads(a.oracle.read_text())
    plan_doc=json.loads(a.plans.read_text())
    plans=plan_doc["plans"]

    # No answer-key leakage is allowed into the planner artifact.
    forbidden={"expected_path","expected_action","selected_path","answer","target_path"}
    for p in plans:
        leaked=forbidden.intersection(p)
        assert not leaked,(p["id"],"oracle leakage",sorted(leaked))
        assert p.get("probes"),(p["id"],"empty probes")

    oracle={c["id"]:c for c in oracle_doc["cases"]}
    assert set(oracle)=={p["id"] for p in plans},"planner/oracle case ID mismatch"

    object_map=json.loads((root/"objects.json").read_text())
    known_paths={o["path"] for o in object_map["objects"]}

    results=[]; passed=0; glyph_calls=0
    for plan in plans:
        case=oracle[plan["id"]]
        assert plan["human_query"]==case["human_query"],(plan["id"],"human query drift")
        expected=case.get("expected_path")
        expected_action=case.get("expected_action","found")
        if expected is not None: assert expected in known_paths,(plan["id"],expected)

        scores=collections.Counter(); evidence=collections.defaultdict(list)
        probe_reports=[]
        for probe in plan["probes"]:
            got=glyph_query(root,probe); glyph_calls+=1
            assert got["rlb2_not_used"] is True,(plan["id"],probe)
            matched=set()
            for hit in got["valid_hits"]:
                key=(hit["object_id"],hit["path"]); matched.add(key)
                evidence[key].append({"probe":probe,"object_offset":hit["object_offset"],"corpus_offset":hit["corpus_offset"]})
            for key in matched: scores[key]+=1
            probe_reports.append({"probe":probe,"matched_objects":sorted({p for _,p in matched}),"valid_count":got["valid_count"]})

        ranked=sorted(scores.items(),key=lambda kv:(-kv[1],kv[0][1],kv[0][0]))
        top_score=ranked[0][1] if ranked else 0
        top=[key for key,score in ranked if score==top_score]
        selected_path=top[0][1] if len(top)==1 else None
        action="found" if selected_path is not None else "not_found" if not ranked else "ambiguous"

        if expected_action=="found":
            ok=(action=="found" and selected_path==expected and top_score==len(plan["probes"]))
        elif expected_action=="ambiguous":
            ok=(action=="ambiguous" and len(top)>1)
        elif expected_action=="not_found":
            ok=(action=="not_found" and not ranked)
        else:
            raise AssertionError((plan["id"],expected_action))
        assert ok,(plan,{"action":action,"selected_path":selected_path,"ranked":ranked,"probes":probe_reports})
        passed+=1
        results.append({"id":plan["id"],"human_query":plan["human_query"],"llm_probes":plan["probes"],"expected_action":expected_action,"expected_path":expected,"action":action,"selected_path":selected_path,"passed":ok})

    report={
        "format":"GLYPH_EXTERNAL_LLM_PLANNER_GATE_V1",
        "planner":plan_doc["planner"],
        "cases":len(plans),
        "cases_passed":passed,
        "all_cases_passed":passed==len(plans),
        "glyph_calls":glyph_calls,
        "planner_artifact_has_oracle_fields":False,
        "retrieval_substrate":"RLB3X+LOC2+object-boundary-filter",
        "important_non_claim":"The plans were generated by an external ChatGPT model and replayed through GLYPH; this is not yet an autonomous on-device LLM invocation inside the vault runtime.",
        "results":results,
    }
    (root/"external-llm-planner-gate.json").write_text(json.dumps(report,sort_keys=True,separators=(",",":"))+"\n")
    print(json.dumps({k:v for k,v in report.items() if k!="results"},sort_keys=True))

if __name__=="__main__": main()
